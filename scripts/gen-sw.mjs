// Post-build: write dist/sw.js that precaches every built file (the app is tiny).
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f !== 'sw.js') files.push(relative(dist, p).split('\\').join('/'));
  }
})(dist);
files.sort();
const h = createHash('sha256');
for (const f of files) h.update(f).update(readFileSync(join(dist, f)));
const version = h.digest('hex').slice(0, 12);
// index.html is cached as './' because static hosts (serve, Vercel cleanUrls) redirect
// /index.html → /, and a redirected response can't be used for navigations.
const assets = ['./', ...files.filter((f) => f !== 'index.html').map((f) => './' + f)];

const sw = `// Generated by scripts/gen-sw.mjs. Precache-everything, cache-first, same-origin only.
const CACHE = 'sharesafe-${version}';
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('sharesafe-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('./', { ignoreSearch: true }).then((r) => r || fetch(req)));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((r) => r || fetch(req)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${assets.length} assets precached, cache ${version}`);
