export type StrKey = keyof typeof STR;

export function t(key: StrKey, lang: Lang, plain: boolean, vars?: Record<string, string | number>): string {
  const entry = STR[key];
  const loc = (lang === 'es' && entry.es) ? entry.es : entry.en;
  let s = plain ? loc.plain : loc.std;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}

